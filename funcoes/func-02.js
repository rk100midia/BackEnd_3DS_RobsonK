// calcula e imprime resultado

function subtração(n1, n2){
    const resultado = n1 - n2
    console.log("resultado subtração: " + resultado)
}

subtração(5, 4)
subtração(4, 2)

//adição

function adição(n1, n2){
    const resultado = n1 + n2
    console.log("resultado adição: " + resultado)
}

adição(15, 10)
adição(20, 10)

//divisão

function divisão(n1, n2){
    const resultado = n1 / n2
    console.log("resultado divisão : " + resultado)
}

divisão(5, 4)
divisão(6, 4)

//multiplicação

function multiplicação(n1, n2){
    const resultado = n1 * n2
    console.log("resultado multiplicação: " + resultado)
}

multiplicação(5, 4)
multiplicação(15, 10)